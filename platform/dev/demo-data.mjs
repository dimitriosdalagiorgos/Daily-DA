export function demoStudentRows() {
  const rows = [["Τάξη", "Αριθμός Μητρώου", "Επώνυμο", "Όνομα", "Όνομα πατέρα", "Όνομα μητέρας"]];
  let am = 9001;
  for (const grade of ["Α", "Β", "Γ"]) {
    for (let i = 0; i < 20; i++) {
      const girl = i % 2 === 1;
      const surname = SURNAMES[i % SURNAMES.length];
      rows.push([grade, am++, girl ? surname.replace(/ΟΣ$/, "ΟΥ").replace(/ΗΣ$/, "Η") : surname,
        (girl ? GIRLS : BOYS)[i % 6], FATHERS[i % 4], MOTHERS[(i + 1) % 4]]);
    }
  }
  return rows;
}

