/** Help for one role: a card per section. */
export function helpView(role) {
  const { sections } = HELP[role];
  return el("div", {}, sections.map(([title, items]) =>
    el("section.card", {}, el("h2", { style: "margin-top:0" }, title),
      el("ul.help", {}, items.map((item) => el("li", {}, ...(Array.isArray(item) ? item : [item])))))));
}

/** Tabs for several roles; the selected one is kept in location.hash when useHash is set. */
export function helpTabs(roles, { useHash = false } = {}) {
  const panel = el("div", { role: "tabpanel" });
  const fromHash = () => (useHash && roles.includes(location.hash.slice(1)) ? location.hash.slice(1) : roles[0]);
  let current = fromHash();
  const nav = el("nav.tabs", { role: "tablist" });
  const draw = () => {
    nav.replaceChildren(...roles.map((r) => el("button", {
      type: "button", role: "tab", "aria-selected": String(r === current),
      onclick: () => { current = r; if (useHash) history.replaceState(null, "", `#${r}`); draw(); },
    }, HELP[r].label)));
    panel.replaceChildren(helpView(current));
  };
  if (useHash) addEventListener("hashchange", () => { current = fromHash(); draw(); });
  draw();
  return el("div", {}, nav, panel);
}
